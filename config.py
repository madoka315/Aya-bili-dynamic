# -*- coding: utf-8 -*-
# B站动态推送 插件配置（本文件在插件目录内，改完需重启 bot 生效）

# 可选：B站 App 登录 access_key（App抓包获取）。
# 游客模式被 B站持续风控时（log 出现"持续风控"字样）配置它可显著提升成功率；留空 = 纯游客模式
ACCESS_KEY = ""

# 可选代理，如 "http://127.0.0.1:7890"，留空直连
PROXY = ""

# ============ 频率（稳定优先档：请求量低、对 B站 尽量不显眼）============
# 成功拉取后的下次轮询间隔（秒）。单 UID 每天约 288 次请求
POLL_INTERVAL = 300

# 被软门控（空包）后的重试间隔（秒）。B站按请求概率放行，靠重试覆盖；
# 心跳为 60s，故实际重试间隔为 60~120s
RETRY_INTERVAL = 60

# gRPC 报错（-352 等）后的退避基数（秒），随连续失败次数倍增（上限 5 倍）
ERROR_BACKOFF = 600

# 连续多少次空包视为「持续风控」，进入长退避并在 log/error 记一条告警
GATE_ALERT_N = 20
GATE_ALERT_BACKOFF = 1800

# 调度器心跳间隔（秒）与每次心跳最多轮询的 UID 数。
# 注意：框架会给每次心跳打两行 INFO（start/completed），这是 Hoshino 行为；
# 心跳间隔就是日志刷屏的下限
TICK_SECONDS = 60
MAX_POLLS_PER_TICK = 2

# 每条动态最多推送的图片数
IMAGES_LIMIT = 3

# 动态展示正文的最大字符数，超出截断并加「……(已截断)」标记；
# 关键词匹配仍用全文，不受此限制影响
TEXT_LIMIT = 500

# ============ 权限 ============
# 普通用户（非群管理）在单个群内最多能关注的 UID 数；群管理及以上不受此限制。
# 改成 0 等于关闭普通用户关注功能。
MAX_USER_SUBS = 1

# ============ 默认订阅（可选） ============
# bot 启动时自动预置的订阅（群号 -> UID 列表），手动取关后重启会被重新加回；
# 不想要某条默认订阅就从这里删除。留空 {} 表示没有默认订阅
# 例：DEFAULT_SUBS = {"123456789": ["353840826"]}
DEFAULT_SUBS = {}
